"""Sharded generation for clusters.

Almost all GPU time in an experiment is the initial answer of every pool model for every item.
Those requests are independent, so they can be generated by many jobs in parallel. Each job
writes its own SQLite cache: SQLite on a shared network file system is not safe for concurrent
writers. The caches are merged, and the ordinary ``routeguard benchmark`` then replays them.

    routeguard generate --config exp.yaml --shard 3/16 --cache shards/3.sqlite   # per job
    routeguard cache-merge shards/*.sqlite --out .routeguard_cache/hf.sqlite
    routeguard benchmark --config exp.yaml                                      # replay

Requests are identified by the same key the benchmark uses (``request_key``), so a merged
cache is hit exactly. Sharding is over the sorted set of unique keys, so shards are disjoint,
balanced, and independent of which job runs where.
"""

from __future__ import annotations

import json
import logging
import os
import sqlite3
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from routeguard.benchmarks.loaders import load_all
from routeguard.config import ExperimentConfig
from routeguard.context import CallContext
from routeguard.models import GenerationCache, ModelPool, ModelSpec
from routeguard.models.cache import CachedLLM, request_key
from routeguard.models.pool import backend_class
from routeguard.pipeline import RouteGuardPipeline
from routeguard.types import GenerationRequest

logger = logging.getLogger(__name__)


@dataclass
class ShardSpec:
    index: int
    count: int

    @classmethod
    def parse(cls, text: str) -> ShardSpec:
        """``"3/16"`` (0-based index), or ``"auto"`` to read a SLURM array job's variables."""
        if text == "auto":
            try:
                index = int(os.environ["SLURM_ARRAY_TASK_ID"])
                count = int(os.environ["SLURM_ARRAY_TASK_COUNT"])
            except KeyError as exc:
                raise ValueError("--shard auto needs SLURM_ARRAY_TASK_ID/COUNT") from exc
            offset = int(os.environ.get("SLURM_ARRAY_TASK_MIN", "0"))
            return cls(index - offset, count)
        try:
            i, n = (int(x) for x in text.split("/"))
        except ValueError as exc:
            raise ValueError(f"--shard must look like 'i/N', got {text!r}") from exc
        if not 0 <= i < n:
            raise ValueError(f"shard index must satisfy 0 <= i < N, got {text!r}")
        return cls(i, n)


def plan_requests(
    config: ExperimentConfig,
    models: Sequence[str] | None = None,
) -> dict[str, dict[str, GenerationRequest]]:
    """Unique initial-answer requests of every system, per model, keyed by cache key.

    Systems whose prompts need fitted components (a learned task classifier) are skipped:
    their few remaining requests are generated by the benchmark itself.
    """
    items = load_all(config.data)
    queries = [it.to_query() for it in items]
    first = config.system_pipeline(config.systems[0])
    specs = [ModelSpec(**m.model_dump()) for m in first.models]
    pool = ModelPool(specs, cache=None)
    wanted = set(models or pool.names)
    unknown = wanted - set(pool.names)
    if unknown:
        raise ValueError(f"Unknown models {sorted(unknown)}; pool is {pool.names}")
    plan: dict[str, dict[str, GenerationRequest]] = {m: {} for m in pool.names if m in wanted}
    seen_prompt_configs: set[str] = set()
    for system in config.systems:
        cfg = config.system_pipeline(system)
        if cfg.analyzer.task_classifier == "learned":
            continue
        signature = json.dumps(cfg.analyzer.model_dump(), sort_keys=True)
        if signature in seen_prompt_configs:
            continue
        seen_prompt_configs.add(signature)
        pipe = RouteGuardPipeline(cfg, pool=pool)
        for q in queries:
            messages = pipe.messages_for(q, pipe.analyze(q))
            ctx = CallContext(pool, q, cfg.seed)
            for model in plan:
                req = ctx._request(
                    model, messages, "initial", 0.0, 0, None, {"strategy": "default"}
                )
                key = request_key(
                    backend_class(pool.spec(model).backend).spec_identity(pool.spec(model)), req
                )
                plan[model][key] = req
    return plan


def generate_shard(
    config: ExperimentConfig,
    shard: ShardSpec,
    cache_path: str | Path,
    models: Sequence[str] | None = None,
) -> dict[str, int]:
    """Generate this shard's requests into ``cache_path``; returns counts per model."""
    plan = plan_requests(config, models)
    cache = GenerationCache(cache_path)
    first = config.system_pipeline(config.systems[0])
    done: dict[str, int] = {}
    for model, requests in plan.items():
        keys = sorted(requests)[shard.index :: shard.count]
        spec = next(ModelSpec(**m.model_dump()) for m in first.models if m.name == model)
        llm = CachedLLM(spec, backend_class(spec.backend), cache)
        logger.info(
            "shard %d/%d: %s has %d of %d requests",
            shard.index,
            shard.count,
            model,
            len(keys),
            len(requests),
        )
        llm.generate_batch([requests[k] for k in keys])
        done[model] = len(keys)
    cache.close()
    return done


def merge_caches(inputs: Sequence[str | Path], output: str | Path) -> int:
    """Merge SQLite generation caches; returns the number of entries in the output."""
    out = GenerationCache(output)
    out.close()
    conn = sqlite3.connect(output)
    for path in inputs:
        if Path(path).resolve() == Path(output).resolve():
            continue
        conn.execute("ATTACH DATABASE ? AS src", (str(path),))
        conn.execute(
            "INSERT OR IGNORE INTO generations SELECT key, model, value FROM src.generations"
        )
        conn.commit()
        conn.execute("DETACH DATABASE src")
    total = int(conn.execute("SELECT COUNT(*) FROM generations").fetchone()[0])
    conn.close()
    return total
